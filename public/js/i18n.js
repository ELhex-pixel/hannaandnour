  var lang = localStorage.getItem('hn-lang');
  if (SUPPORTED.indexOf(lang) === -1) {
    lang = navigator.language ? (navigator.language.toLowerCase().indexOf('fr') === 0 ? 'fr' : (navigator.language.toLowerCase().indexOf('ar') === 0 ? 'ar' : 'en')) : 'en';
  }

  function applyDir() {
    var isAr = lang === 'ar';
    document.documentElement.lang = lang;
    document.documentElement.dir = isAr ? 'rtl' : 'ltr';
    document.documentElement.classList.toggle('rtl', isAr);

    if (isAr) {
      var link = document.getElementById('arabicFont');
      if (!link) {
        link = document.createElement('link');
        link.id = 'arabicFont';
        link.rel = 'stylesheet';
        link.href = 'fonts/cairo.css';
        document.head.appendChild(link);
      }
    }
  }

  function t(key, params) {
    var dict = DICT[lang] || DICT.en;
    var str = dict[key] !== undefined ? dict[key] : (DICT.en[key] !== undefined ? DICT.en[key] : key);
    if (params) {
      Object.keys(params).forEach(function(p) {
        str = str.split('{' + p + '}').join(params[p]);
      });
    }
    if (key === 'announce' || key === 'metaShipText' || key === 'announcePromo') {
      if (str.indexOf('{ship}') >= 0) str = str.split('{ship}').join(shipStr());
      str = applySymbol(str);
    }
    return str;
  }

  var SHIP_THRESHOLD = 75;

  // Sets the "free shipping from" amount (in currency units) from /api/config,
  // e.g. 80 for a 8000-cents threshold.
  function setShipThreshold(cents) {
    var v = parseInt(cents, 10);
    if (!isNaN(v) && v > 0) SHIP_THRESHOLD = v / 100;
  }

  // Formats the ship threshold for the current language + currency symbol.
  function shipStr() {
    var sym = window.HN && typeof window.HN.symbol === 'function' ? window.HN.symbol() : '$';
    var v = Math.round(SHIP_THRESHOLD * 100) / 100;
    var amount = (v % 1 === 0) ? String(v) : v.toFixed(2);
    if (lang === 'fr') return amount + ' ' + sym;
    if (lang === 'ar') return amount + ' ' + (sym === '$' ? 'دولارًا' : sym);
    return sym + amount;
  }

  // Replaces the hard-coded currency amount ($75 / 75 $ / 75 دولارًا) with the
  // admin-selected currency symbol so the copy matches the live prices.
  function applySymbol(str) {
    var sym = window.HN && typeof window.HN.symbol === 'function' ? window.HN.symbol() : '$';
    if (sym === '$') return str;
    return str.split('$').join(sym).split('دولارًا').join(sym);
  }

  function refreshCurrencyLabels() {
    ['announce', 'metaShipText'].forEach(function (key) {
      document.querySelectorAll('[data-i18n="' + key + '"]').forEach(function (el) {
        el.textContent = t(key);
      });
    });
  }

  function applyTranslations() {
    applyDir();

    document.querySelectorAll('[data-i18n]').forEach(function(el) {
      var key = el.getAttribute('data-i18n');
      el.textContent = t(key);
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el) {
      var key = el.getAttribute('data-i18n-placeholder');
      el.setAttribute('placeholder', t(key));
    });

    document.querySelectorAll('[data-i18n-aria-label]').forEach(function(el) {
      var key = el.getAttribute('data-i18n-aria-label');
      el.setAttribute('aria-label', t(key));
    });
  }

  function setLang(nextLang) {
    if (SUPPORTED.indexOf(nextLang) === -1) return;
    lang = nextLang;
    localStorage.setItem('hn-lang', lang);
    applyTranslations();
    document.dispatchEvent(new CustomEvent('langchange', { detail: lang }));

    var switchers = document.querySelectorAll('.lang-switcher');
    switchers.forEach(function(sel) {
      sel.value = lang;
    });
  }

  window.I18n = {
    lang: function() { return lang; },
    t: t,
    setLang: setLang,
    apply: applyTranslations,
    refreshCurrency: refreshCurrencyLabels,
    setShipThreshold: setShipThreshold
  };

  document.addEventListener('DOMContentLoaded', function() {
    applyTranslations();

    document.querySelectorAll('.lang-switcher').forEach(function(sel) {
      sel.value = lang;
      sel.addEventListener('change', function() {
        setLang(this.value);
      });
    });
  });

